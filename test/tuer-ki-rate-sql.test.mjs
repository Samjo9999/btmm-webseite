// PGlite-Test für docs/tuer-ki/tuer_ki_rate_limit.sql (nicht anwenden in Prod).
import test from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { PGlite } from '@electric-sql/pglite'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const sqlPfad = join(root, 'docs/tuer-ki/tuer_ki_rate_limit.sql')

async function neueDb() {
  const db = new PGlite()
  await db.exec(`
    do $$ begin
      if not exists (select 1 from pg_roles where rolname = 'anon') then create role anon nologin; end if;
      if not exists (select 1 from pg_roles where rolname = 'authenticated') then create role authenticated nologin; end if;
      if not exists (select 1 from pg_roles where rolname = 'service_role') then create role service_role nologin; end if;
    end $$;
    create schema if not exists cron;
    create table if not exists cron.job (
      jobid int generated by default as identity primary key,
      jobname text
    );
    create or replace function cron.unschedule(jobid int) returns void language plpgsql as $$
    begin
      delete from cron.job where cron.job.jobid = unschedule.jobid;
    end $$;
    create or replace function cron.schedule(name text, sched text, cmd text) returns int language plpgsql as $$
    begin
      insert into cron.job(jobname) values (name);
      return 1;
    end $$;
  `)
  await db.exec(readFileSync(sqlPfad, 'utf8'))
  return db
}

test('SQL: Funktion zaehlt pro Hash, Purge nach 24 Stunden, kein Salz, kein Klartext-IP', async () => {
  const db = await neueDb()
  try {
    const eins = await db.query(`select * from public.tuer_ki_rate_zaehle('abc')`)
    assert.deepEqual(eins.rows, [{ stunde: 1, tag: 1 }])
    const zwei = await db.query(`select * from public.tuer_ki_rate_zaehle('abc')`)
    assert.deepEqual(zwei.rows, [{ stunde: 2, tag: 2 }])
    const ander = await db.query(`select * from public.tuer_ki_rate_zaehle('def')`)
    assert.deepEqual(ander.rows, [{ stunde: 1, tag: 1 }])

    const spalten = await db.query(`
      select column_name from information_schema.columns
      where table_schema = 'public' and table_name = 'tuer_ki_rate'
      order by 1
    `)
    assert.deepEqual(spalten.rows.map((r) => r.column_name), ['anzahl', 'erstellt', 'fenster', 'ip_hash'])
    assert.equal(spalten.rows.some((r) => r.column_name === 'salz'), false)

    const zeilen = await db.query(`select ip_hash, anzahl from public.tuer_ki_rate order by ip_hash`)
    assert.deepEqual(zeilen.rows, [
      { ip_hash: 'abc', anzahl: 2 },
      { ip_hash: 'def', anzahl: 1 },
    ])
    assert.equal(JSON.stringify(zeilen.rows).includes('203.0.113'), false)

    await db.exec(`
      update public.tuer_ki_rate
        set erstellt = now() - interval '25 hours', fenster = date_trunc('hour', now() - interval '25 hours')
      where ip_hash = 'abc'
    `)
    const nachPurge = await db.query(`select * from public.tuer_ki_rate_zaehle('abc')`)
    assert.deepEqual(nachPurge.rows, [{ stunde: 1, tag: 1 }])
    const rest = await db.query(`select ip_hash, anzahl from public.tuer_ki_rate order by ip_hash`)
    assert.deepEqual(rest.rows, [
      { ip_hash: 'abc', anzahl: 1 },
      { ip_hash: 'def', anzahl: 1 },
    ])

    const jobs = await db.query(`select jobname from cron.job`)
    assert.deepEqual(jobs.rows, [{ jobname: 'tuer_ki_rate_purge' }])
  } finally {
    await db.close()
  }
})

test('SQL: revoke table und function von public/anon/authenticated, nur service_role darf ausfuehren', async () => {
  const db = await neueDb()
  try {
    const priv = await db.query(`
      select
        has_table_privilege('anon', 'public.tuer_ki_rate', 'SELECT') as anon_select,
        has_table_privilege('anon', 'public.tuer_ki_rate', 'INSERT') as anon_insert,
        has_table_privilege('anon', 'public.tuer_ki_rate', 'UPDATE') as anon_update,
        has_table_privilege('anon', 'public.tuer_ki_rate', 'DELETE') as anon_delete,
        has_table_privilege('authenticated', 'public.tuer_ki_rate', 'SELECT') as auth_select,
        has_table_privilege('authenticated', 'public.tuer_ki_rate', 'INSERT') as auth_insert,
        has_table_privilege('public', 'public.tuer_ki_rate', 'SELECT') as public_select,
        has_table_privilege('service_role', 'public.tuer_ki_rate', 'SELECT') as sr_select,
        has_table_privilege('service_role', 'public.tuer_ki_rate', 'INSERT') as sr_insert,
        has_function_privilege('anon', 'public.tuer_ki_rate_zaehle(text)', 'EXECUTE') as anon_exec,
        has_function_privilege('authenticated', 'public.tuer_ki_rate_zaehle(text)', 'EXECUTE') as auth_exec,
        has_function_privilege('public', 'public.tuer_ki_rate_zaehle(text)', 'EXECUTE') as public_exec,
        has_function_privilege('service_role', 'public.tuer_ki_rate_zaehle(text)', 'EXECUTE') as sr_exec
    `)
    const p = priv.rows[0]
    assert.equal(p.anon_select, false)
    assert.equal(p.anon_insert, false)
    assert.equal(p.anon_update, false)
    assert.equal(p.anon_delete, false)
    assert.equal(p.auth_select, false)
    assert.equal(p.auth_insert, false)
    assert.equal(p.public_select, false)
    assert.equal(p.sr_select, true)
    assert.equal(p.sr_insert, true)
    assert.equal(p.anon_exec, false)
    assert.equal(p.auth_exec, false)
    assert.equal(p.public_exec, false)
    assert.equal(p.sr_exec, true)
  } finally {
    await db.close()
  }
})
